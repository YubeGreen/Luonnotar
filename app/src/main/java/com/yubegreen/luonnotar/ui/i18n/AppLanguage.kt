package com.yubegreen.luonnotar.ui.i18n

import android.content.Context
import android.view.View
import android.view.ViewGroup
import android.widget.TextView

enum class AppLanguage(val storedValue: String) {
    CHINESE("zh-CN"),
    ENGLISH("en")
}

object AppLanguageStore {
    private const val PREFS = "luonnotar_language"
    private const val KEY_LANGUAGE = "language"

    private fun preferences(context: Context) =
        context.createDeviceProtectedStorageContext()
            .getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    fun current(context: Context): AppLanguage {
        val stored = preferences(context).getString(KEY_LANGUAGE, null)
        return AppLanguage.entries.firstOrNull { it.storedValue == stored }
            ?: AppLanguage.CHINESE
    }

    fun set(context: Context, language: AppLanguage) {
        preferences(context)
            .edit()
            .putString(KEY_LANGUAGE, language.storedValue)
            .apply()
    }

    fun isEnglish(context: Context): Boolean = current(context) == AppLanguage.ENGLISH
}

object UiText {
    fun choose(context: Context, zh: CharSequence, en: CharSequence): CharSequence =
        if (AppLanguageStore.isEnglish(context)) en else zh

    fun localize(context: Context, value: CharSequence?): CharSequence? {
        if (value == null || !AppLanguageStore.isEnglish(context)) return value
        val source = value.toString()
        if (!source.any { it in '\u3400'..'\u9fff' }) return value
        return EnglishCatalog.translate(source)
    }

    fun localizeTree(context: Context, root: View) {
        if (!AppLanguageStore.isEnglish(context)) return
        if (root is TextView) {
            root.text = localize(context, root.text) ?: root.text
            root.contentDescription = localize(context, root.contentDescription)
        } else {
            root.contentDescription = localize(context, root.contentDescription)
        }
        if (root is ViewGroup) {
            for (i in 0 until root.childCount) {
                localizeTree(context, root.getChildAt(i))
            }
        }
    }
}

